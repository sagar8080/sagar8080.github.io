import { mkdir, readdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const originals = new URL('../public/photography/', import.meta.url)
const derivatives = new URL('../public/portfolio/', import.meta.url)
const manifest = new URL('../src/components/site/photo-assets.ts', import.meta.url)
const tiers = [360, 720, 1080, 1440]

const files = (await readdir(originals))
  .filter((file) => /^\d+\.jpeg$/.test(file))
  .sort((left, right) => Number.parseInt(left, 10) - Number.parseInt(right, 10))

await mkdir(derivatives, { recursive: true })
const photos = {}
for (const file of files) {
  const name = file.replace(/\.jpeg$/, '')
  const image = sharp(fileURLToPath(new URL(file, originals)))
  const { autoOrient: { width, height } } = await image.metadata()
  const maximum = Math.min(width, tiers.at(-1))
  const widths = [...tiers.filter((size) => size < maximum * .92), maximum]
  const preferred = widths.reduce((best, size) =>
    Math.abs(size - 720) < Math.abs(best - 720) ? size : best,
  )
  const sources = await Promise.all(widths.map(async (size) => {
    const derivative = size === preferred ? `${name}.webp` : `${name}-${size}.webp`
    await image.clone().autoOrient()
      .resize({ width: size, withoutEnlargement: true })
      .withIccProfile('srgb', { attach: false })
      .webp({ quality: size <= 360 ? 89 : size <= 720 ? 86 : 83, effort: 5, smartSubsample: true })
      .toFile(fileURLToPath(new URL(derivative, derivatives)))
    return `/portfolio/${derivative} ${size}w`
  }))
  photos[`/photography/${file}`] = { width, height, srcSet: sources.join(', ') }
}

await writeFile(manifest, `// Generated by scripts/generate-photo-previews.mjs.
type PhotoAsset = { width: number; height: number; srcSet: string }

export const photoAssets: Partial<Record<string, PhotoAsset>> = ${JSON.stringify(photos, null, 2)}
`)
